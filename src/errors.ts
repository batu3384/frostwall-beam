export function translateError(raw: string, t: (key: string) => string): string {
  const lower = raw.toLowerCase();
  for (const [needle, key] of ERROR_RULES) {
    if (lower.includes(needle.toLowerCase())) {
      return t(key);
    }
  }
  return raw;
}
